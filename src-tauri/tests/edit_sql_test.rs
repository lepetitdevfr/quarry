/// `select user_id, group_id, role from memberships`, the key being
/// both id columns.
fn memberships() -> EditInfo {
    EditInfo {
        editable: true,
        reason: None,
        insertable: true,
        insert_reason: None,
        schema: Some("public".to_string()),
        table: Some("memberships".to_string()),
        pk: vec![
            PkColumn {
                name: "user_id".to_string(),
                result_index: 0,
            },
            PkColumn {
                name: "group_id".to_string(),
                result_index: 1,
            },
        ],
        columns: vec![
            read_only(),
            read_only(),
            editable("role", "\"pg_catalog\".\"text\""),
        ],
    }
}

#[test]
fn a_composite_key_puts_every_column_in_the_where() {
    let info = memberships();

    let edits = vec![RowEdit {
        row: 0,
        pk: vec!["7".to_string(), "9".to_string()],
        cells: vec![CellEdit {
            column: 2,
            value: Some("admin".to_string()),
        }],
    }];

    let statements = build_updates(&info, &edits).expect("should build");
    assert!(
        statements[0].sql.contains("where \"user_id\" = $2")
            && statements[0].sql.contains("and \"group_id\" = $3"),
        "sql was: {}",
        statements[0].sql
    );
    assert_eq!(
        statements[0].params,
        vec![
            Some("admin".to_string()),
            Some("7".to_string()),
            Some("9".to_string())
        ]
    );
}

#[test]
