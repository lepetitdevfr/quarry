#[test]
fn an_enum_offers_its_labels_in_declaration_order() {
    // Postgres reports enum labels in the order they were declared,
    // which is the type's own sort order — not alphabetical.
    let mood = Type::new(
        "mood".to_string(),
        16400,
        Kind::Enum(vec![
            "sad".to_string(),
            "ok".to_string(),
            "happy".to_string(),
        ]),
        "public".to_string(),
    );

    assert_eq!(
        value_choices(&mood),
        Some(vec![
            "sad".to_string(),
            "ok".to_string(),
            "happy".to_string()
        ])
    );
}

